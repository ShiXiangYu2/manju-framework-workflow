def build_beats():
    rows = [BEAT_HEADER]
    for n in range(1, 61):
        seg = next(s for s, a, b in SEGMENTS if a <= n <= b)
        unit = "U1" if n <= 20 else ("U2" if n <= 40 else "U3")
        scene = SCENES[(n - 1) % len(SCENES)]
        hook = HOOKS[(n - 1) % len(HOOKS)]
        entering = ("开场即受压：主角被当众指认冒领，物证在对方手里" if n == 1
                    else "承接债%d：%s，主角持半份物证，对手已起疑" % (n - 1, scene))
        out = "欠债%d：对方封住下一条路，EP%d 开场必须接住" % (n, n + 1)
        rows.append([
            n, seg, unit,
            entering,
            "对方正在销毁第%d份证据，时限只剩这一场" % (n % 7 + 1),
            "让对手在本集结束前承认物证来源",
            "设局者握有行规解释权与会场调度权",
            "因上集留下的误信，主角亮半份物证，对手用行规反制，逼主角换策",
            "旧解释被现场证据推翻，关系权力位置翻转",
            "当众反将一次，对手付出可见代价并当众失面",
            "新债：授意者身份只露出半张脸，需在后续集补齐",
            out, hook, "Y" if n in WALLS else "", "群战与多人同框不排",
        ])
    return tsv(rows)


